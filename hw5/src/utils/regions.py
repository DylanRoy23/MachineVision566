def bundled_outlines(name):
    scale = np.array([406 / 162, 720 / 288])
    return {index: np.rint(np.array(vertices) * scale).astype(np.int32)
            for index, vertices in PREVIEW_OUTLINES.get(name, {}).items()}


def outline_mask(shape, outline, margin=0):
    mask = np.zeros(shape, np.uint8)
    cv2.fillPoly(mask, [np.asarray(outline, dtype=np.int32)], 255)
    if margin:
        mask = cv2.dilate(mask, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * margin + 1,) * 2))
    return mask
